// TestRenderMessagesFixedLeafSiblingRepeats proves E5's hardest S1 shape:
// a fixed leaf followed by two independent sibling repeat groups at the same
// list level (S1F19: L[3]{ <OBJTYPE> L{<OBJID>...} L{<ATTRID>...} }). Only the
// final repeat (attrids) is variadic; the non-final repeat (objids) renders as
// a []secs2.Item slice, and the leaf renders ahead of both. The body wraps each
// repeat in its own secs2.L(...) and forwards the leaf unwrapped, per Task 6's
// Repeat/Variadic split and Task 7's three-way params helper.
func TestRenderMessagesFixedLeafSiblingRepeats(t *testing.T) {
	items := paramsItems()
	mf := MessageFile{Stream: 1, Messages: []Message{{
		Function: 19, Name: "Get Attribute", Mnemonic: "GA",
		Direction: "host-to-equipment", Description: "Host requests attributes of an object.",
		Exception: "None", Source: "e5",
		Bodies: []Body{
			{
				Actor: "both", ReplyExpected: true,
				Structure: &StructureNode{Type: "list", Items: []StructureNode{
					{Item: "OBJTYPE"},
					{Type: "list", Repeat: "objids", Of: &StructureNode{Item: "OBJID"}},
					{Type: "list", Repeat: "attrids", Of: &StructureNode{Item: "ATTRID"}},
				}},
			},
		},
	}}}
	out, err := renderMessages(mf, items)
	require.NoError(t, err)
	src := string(out)

	require.Contains(t, src, "func S1F19(objtype secs2.Item, objids []secs2.Item, attrids ...secs2.Item) secs2.SECS2Message {\n"+
		"\treturn secs2.NewMessage(1, 19, true, secs2.L(objtype, secs2.L(objids...), secs2.L(attrids...)))\n}")
}

// TestRenderMessagesSiblingRepeatsOfLists proves two sibling repeat groups
// where each repeat element is itself a multi-item list (S1F20:
// L[2]{ L{objects...} L{errors...} }). Each repeat still contributes a single
// caller-supplied secs2.Item parameter (the walker never recurses into a
// repeat's Of), so the nested-list element shape does not leak into the
// signature. The non-final repeat (objects) is a []secs2.Item slice; only the
// final repeat (errors) is variadic.
func TestRenderMessagesSiblingRepeatsOfLists(t *testing.T) {
	items := paramsItems()
	mf := MessageFile{Stream: 1, Messages: []Message{{
		Function: 20, Name: "Attribute Data", Mnemonic: "AD",
		Direction: "equipment-to-host", Description: "Equipment returns object attribute data.",
		Exception: "None", Source: "e5",
		Bodies: []Body{
			{
				Actor: "both", ReplyExpected: false,
				Structure: &StructureNode{Type: "list", Items: []StructureNode{
					{Type: "list", Repeat: "objects", Of: &StructureNode{Type: "list", Items: []StructureNode{{Item: "OBJTYPE"}}}},
					{Type: "list", Repeat: "errors", Of: &StructureNode{Type: "list", Items: []StructureNode{{Item: "OBJID"}}}},
				}},
			},
		},
	}}}
	out, err := renderMessages(mf, items)
	require.NoError(t, err)
	src := string(out)

	require.Contains(t, src, "func S1F20(objects []secs2.Item, errors ...secs2.Item) secs2.SECS2Message {\n"+
		"\treturn secs2.NewMessage(1, 20, false, secs2.L(secs2.L(objects...), secs2.L(errors...)))\n}")
}

