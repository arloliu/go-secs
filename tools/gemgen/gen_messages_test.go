// TestRenderMessagesNestedListEnumLeaf proves the nested-list + enum-leaf
// body path: S1F14's body is a top-level list whose first child is a fixed
// enum leaf (COMMACK) and whose second child is itself a nested list
// (MDLN/SOFTREV). The generated parameter for the enum leaf must be the
// named type COMMACK (not the bare byte), and the body must convert it back
// to byte at the secs2.B(...) call site, per Task 6's BuildParams/BodyExpr.
// S1F14Host proves the per-actor variant: only mdln/softrev drop for the
// host variant, since COMMACK is shared across both actors.
func TestRenderMessagesNestedListEnumLeaf(t *testing.T) {
	items := paramsItems()
	mf := MessageFile{Stream: 1, Messages: []Message{{
		Function: 14, Name: "Establish Communications Request Acknowledge", Mnemonic: "CRA",
		Direction: "bidirectional", Description: "Reply to Establish Communications Request.",
		Exception: "None", Source: "e5",
		Bodies: []Body{
			{
				Actor: "equipment", ReplyExpected: false,
				Structure: &StructureNode{Type: "list", Items: []StructureNode{
					{Item: "COMMACK"},
					{Type: "list", Items: []StructureNode{{Item: "MDLN"}, {Item: "SOFTREV"}}},
				}},
			},
			{
				Actor: "host", ReplyExpected: false,
				Structure: &StructureNode{Type: "list", Items: []StructureNode{
					{Item: "COMMACK"},
					{Type: "list", Items: []StructureNode{}},
				}},
			},
		},
	}}}
	out, err := renderMessages(mf, items)
	require.NoError(t, err)
	src := string(out)

	require.Contains(t, src, "func S1F14(commack COMMACK, mdln string, softrev string) secs2.SECS2Message {\n"+
		"\treturn secs2.NewMessage(1, 14, false, secs2.L(secs2.B(byte(commack)), secs2.L(secs2.A(mdln), secs2.A(softrev))))\n}")
	require.Contains(t, src, "func S1F14Host(commack COMMACK) secs2.SECS2Message {\n"+
		"\treturn secs2.NewMessage(1, 14, false, secs2.L(secs2.B(byte(commack)), secs2.L()))\n}")
}

