func TestRenderMessagesHeaderOnly(t *testing.T) {
	items := map[string]Item{}
	mf := MessageFile{Stream: 1, Messages: []Message{{
		Function: 1, Name: "Are You There Request", Mnemonic: "R",
		Direction: "bidirectional", Description: "Establishes if the equipment is on-line.",
		Exception: "None", Source: "e5",
		Bodies: []Body{{Actor: "both", ReplyExpected: true, Structure: nil}},
	}}}
	out, err := renderMessages(mf, items)
	require.NoError(t, err)
	src := string(out)
	require.Contains(t, src, "// Code generated by gemgen; DO NOT EDIT.")
	require.Contains(t, src, "package gem")
	require.Contains(t, src, "func S1F1() secs2.SECS2Message {")
	require.Contains(t, src, "return secs2.NewMessage(1, 1, true, secs2.NewEmptyItem())")
}

// TestRenderMessagesFixedListActorVariants proves the fixed-list body +
// per-actor variant path: S1F2 (equipment sends a two-item list) and
// S1F2Host (host sends an empty list) share the same stream/function but
// render as two distinct functions, with the host actor's function name
// carrying the "Host" suffix.
func TestRenderMessagesFixedListActorVariants(t *testing.T) {
	items := testItems()
	mf := MessageFile{Stream: 1, Messages: []Message{{
		Function: 2, Name: "On Line Data", Mnemonic: "D",
		Direction: "bidirectional", Description: "Data signifying that the equipment is alive.",
		Exception: "The host sends a zero-length list to the equipment.", Source: "e5",
		Bodies: []Body{
			{
				Actor: "equipment", ReplyExpected: false,
				Structure: &StructureNode{Type: "list", Items: []StructureNode{{Item: "MDLN"}, {Item: "SOFTREV"}}},
			},
			{
				Actor: "host", ReplyExpected: false,
				Structure: &StructureNode{Type: "list", Items: []StructureNode{}},
			},
		},
	}}}
	out, err := renderMessages(mf, items)
	require.NoError(t, err)
	src := string(out)

	require.Contains(t, src, "func S1F2(mdln string, softrev string) secs2.SECS2Message {\n\treturn secs2.NewMessage(1, 2, false, secs2.L(secs2.A(mdln), secs2.A(softrev)))\n}")
	require.Contains(t, src, "func S1F2Host() secs2.SECS2Message {\n\treturn secs2.NewMessage(1, 2, false, secs2.L())\n}")
}

