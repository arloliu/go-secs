// TestMessageDoc covers the messageDoc godoc-line helper directly: a
// source: external message must carry the trailing disclaimer paragraph
// (preceded by its own blank line), and a non-external message must not.
func TestMessageDoc(t *testing.T) {
	items := map[string]Item{}
	body := Body{Actor: "both", ReplyExpected: false, Structure: nil}

	t.Run("external source appends disclaimer", func(t *testing.T) {
		m := Message{
			Function: 12, Name: "Status Variable Namelist Reply", Mnemonic: "SVNR",
			Direction: "equipment-to-host", Description: "Equipment reports the namelist.",
			Exception: "None", Source: "external",
		}
		doc := messageDoc("S1F12", "S1F12", m, body, items)

		require.Contains(t, doc, externalSourceDisclaimer)

		idx := indexOf(doc, externalSourceDisclaimer)
		require.Greater(t, idx, 0, "disclaimer must not be the first line")
		require.Equal(t, "", doc[idx-1], "a blank line must precede the disclaimer paragraph")

		// Body: and Exception: paragraphs are still separated by a genuine
		// blank line even when the disclaimer is appended afterward.
		bodyIdx := indexOfPrefix(doc, "Body:")
		excIdx := indexOfPrefix(doc, "Exception:")
		require.Equal(t, "", doc[bodyIdx+1])
		require.Equal(t, excIdx, bodyIdx+2)
	})

	t.Run("non-external source has no disclaimer", func(t *testing.T) {
		m := Message{
			Function: 1, Name: "Are You There Request", Mnemonic: "R",
			Direction: "bidirectional", Description: "Establishes if the equipment is on-line.",
			Exception: "None", Source: "e5",
		}
		doc := messageDoc("S1F1", "S1F1", m, body, items)

		for _, line := range doc {
			require.NotContains(t, line, "reconstructed from an external reference")
		}
	})
}

func indexOf(lines []string, s string) int {
	for i, l := range lines {
		if l == s {
			return i
		}
	}

	return -1
}

func indexOfPrefix(lines []string, prefix string) int {
	for i, l := range lines {
		if strings.HasPrefix(l, prefix) {
			return i
		}
	}

	return -1
}
